#!/usr/bin/env python3
"""core/agent: bundle browser, native and core agent sources into one Frida script (contracts/agent-bundle.md)."""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

HEADER = "// GENERATED by core/agent/build_agent.py — do not edit"
TOP_LEVEL_RE = re.compile(r"^(?:async\s+)?(?:function\*?|const|let|var|class)\s+([A-Za-z_$][\w$]*)", re.M)
DEFAULT_ROOT = Path(__file__).resolve().parents[2]
PRIMITIVE_CODES = {
    "boolean": "Z", "byte": "B", "char": "C", "short": "S", "int": "I", "long": "J", "float": "F", "double": "D",
}
PLATFORM_PREFIXES = ("java.", "javax.", "android.", "dalvik.", "kotlin.")


class BuildError(Exception):
    pass


def read(root: Path, relative: str) -> str:
    path = root / relative
    if not path.is_file():
        raise BuildError(f"missing file {relative}")
    return path.read_text(encoding="utf-8")


def render_vocabulary(root: Path, entry: dict) -> str:
    types = json.loads(read(root, entry.get("file", "core/events/event_types.json")))
    lines = ["const EVENT_TYPE = Object.freeze({"]
    lines += [f"  {name}: {json.dumps(value)}," for name, value in types.items()]
    lines.append("});")
    return "\n".join(lines)


def render_browser_source(root: Path, entry: dict) -> str:
    files = entry.get("files") or [entry["file"]]
    parts = []
    for relative in files:
        text = read(root, relative)
        if "${" in text:
            raise BuildError(f"template literal in browser source {relative}")
        parts.append(text.rstrip("\n"))
    source = "\n".join(parts)
    if entry.get("wrap") == "iife":
        source = "(function() {\n" + source + "\n})();"
    return source


def jvm_name(java_type: str) -> str:
    """Dotted Java type -> Class.getName() form used by Frida overloads: int[] -> [I, a.B[] -> [La.B;."""
    dims = java_type.count("[]")
    base = java_type.replace("[]", "")
    if dims == 0:
        return base
    return "[" * dims + (PRIMITIVE_CODES.get(base) or f"L{base};")


def static_targets(artifact: dict | None) -> list[dict]:
    """One hook target per exposed method in the static artifact (contracts/agent-static-bridges.md)."""
    if not isinstance(artifact, dict) or artifact.get("schema") != 1 or artifact.get("status") != "completed":
        return []
    names: dict[str, set[str]] = {}
    exposed: list[tuple[str, dict]] = []
    for registration in artifact.get("registrations") or []:
        classes = [registration["class_name"]] if registration.get("class_name") else registration.get("candidate_classes") or []
        for class_name in classes:
            if registration.get("name"):
                names.setdefault(class_name, set()).add(registration["name"])
        exposed += [(registration["class_name"], m) for m in registration.get("methods") or [] if registration.get("class_name")]
    exposed += [(c["class_name"], m) for c in artifact.get("bridge_classes") or [] for m in c.get("methods") or []]

    targets: dict[tuple, dict] = {}
    for owner, method in exposed:
        declared = method.get("declared_in") or owner
        if declared.startswith(PLATFORM_PREFIXES):
            continue  # never hook framework classes such as java.lang.Object (pre-API-17 exposure)
        args = [jvm_name(param) for param in method.get("params") or []]
        key = (declared, method["name"], tuple(args))
        interface = sorted(names.get(owner, set()) | names.get(declared, set()))
        if key in targets:
            interface = sorted(set(interface) | set(targets[key]["interfaceNames"]))
        targets[key] = {"className": declared, "method": method["name"], "args": args, "interfaceNames": interface}
    return [
        {**t, "interfaceName": t["interfaceNames"][0] if len(t["interfaceNames"]) == 1 else None}
        for _, t in sorted(targets.items())
    ]


def render_static_bridges(artifact: dict | None) -> str:
    targets = [{k: t[k] for k in ("className", "method", "args", "interfaceName")} for t in static_targets(artifact)]
    if not targets:
        return "const STATIC_BRIDGES = Object.freeze([]);"
    body = "\n".join(f"  {json.dumps(target, sort_keys=True)}," for target in targets)
    return "const STATIC_BRIDGES = Object.freeze([\n" + body + "\n]);"


def load_static(path: Path | None) -> dict | None:
    """The static discovery artifact; an unreadable one only disables pre-instrumentation."""
    if path is None:
        return None
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError, json.JSONDecodeError) as error:
        print(f"build_agent: ignoring static bridges {path}: {error}", file=sys.stderr)
        return None


def build(root: Path, manifest_path: Path, static: dict | None = None) -> str:
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    entries = manifest["entries"]

    vocabulary = [render_vocabulary(root, e) for e in entries if e["kind"] == "vocabulary"]
    browser = [(e["name"], render_browser_source(root, e)) for e in entries if e["kind"] == "browser"]
    sources = [e["file"] for e in entries if e["kind"] == "source"]

    if browser:
        body = "\n".join(f"  {name}: {json.dumps(text)}," for name, text in browser)
        browser_block = "const BROWSER_SOURCES = Object.freeze({\n" + body + "\n});"
    else:
        browser_block = "const BROWSER_SOURCES = Object.freeze({});"

    declared = {"EVENT_TYPE": "<generated>", "BROWSER_SOURCES": "<generated>", "STATIC_BRIDGES": "<generated>"}
    chunks = [HEADER, *vocabulary, browser_block, render_static_bridges(static)]
    for relative in sources:
        text = read(root, relative)
        for name in TOP_LEVEL_RE.findall(text):
            if name in declared:
                raise BuildError(f"duplicate top-level name '{name}' ({declared[name]} and {relative})")
            declared[name] = relative
        chunks.append(f"// --- {relative}\n" + text.rstrip("\n"))

    return "\n\n".join(chunks) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=DEFAULT_ROOT, help="Directory containing browser/, native/ and core/.")
    parser.add_argument("--manifest", type=Path, default=None, help="Manifest path (default: <root>/core/agent/manifest.json).")
    parser.add_argument("--out", type=Path, required=True, help="Output path for the bundled agent.")
    parser.add_argument(
        "--static-bridges", type=Path, default=None, help="Static discovery artifact whose bridge methods are hooked at startup."
    )
    args = parser.parse_args(argv)

    root = args.root.resolve()
    manifest = args.manifest or root / "core" / "agent" / "manifest.json"
    try:
        output = build(root, manifest, load_static(args.static_bridges))
    except BuildError as error:
        print(f"build_agent: {error}", file=sys.stderr)
        return 1

    args.out.parent.mkdir(parents=True, exist_ok=True)
    with args.out.open("w", encoding="utf-8", newline="\n") as handle:
        handle.write(output)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
